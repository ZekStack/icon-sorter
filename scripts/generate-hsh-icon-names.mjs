import { readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import process from "node:process"
import { fileURLToPath } from "node:url"

const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  ".."
)
const stylesheetPath = path.join(
  repositoryRoot,
  "public/hsh-icons/hsh_icon.css"
)
const outputPath = path.join(
  repositoryRoot,
  "src/lib/hsh-icon-names.generated.ts"
)

const stylesheet = await readFile(stylesheetPath, "utf8")
const names = [
  ...stylesheet.matchAll(/\.ico-hsh-([a-z0-9-]+):before\s*\{/g),
].map((match) => match[1])
const uniqueNames = [...new Set(names)].sort()

if (names.length === 0 || uniqueNames.length !== names.length) {
  throw new Error(
    "HsH icon stylesheet must contain unique .ico-hsh-<name>:before selectors."
  )
}

const generatedNames = uniqueNames
  .map((name) => `  ${JSON.stringify(name)},`)
  .join("\n")
const generated = `// Generated by scripts/generate-hsh-icon-names.mjs. Do not edit directly.
export const hshIconNames = [
${generatedNames}
] as const
`

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "")
  if (current !== generated) {
    throw new Error(
      "Generated HsH icon catalog is stale. Run pnpm generate:hsh-icons."
    )
  }
} else {
  await writeFile(outputPath, generated)
}
